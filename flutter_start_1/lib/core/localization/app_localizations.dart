  String? getString(String key) {
  try {
    final languageCode = locale.languageCode;

    // 1) Try the requested language
    final direct = _localizedValues[languageCode]?[key];
    if (direct != null) return direct;

    // 2) Fall back to English if the current language is missing the key
    if (languageCode != 'en') {
      final fallback = _localizedValues['en']?[key];
      if (fallback != null) return fallback;
    }

    // 3) Unknown key — return null (callers use `?? "..."`) instead of crashing
    debugPrint('⚠️  Missing translation key: "$key" (locale: $languageCode)');
    return null;
  } catch (e, st) {
    debugPrint('⚠️  getString("$key") failed: $e\n$st');
    return null;
  }
}
